CREATE TABLE IF NOT EXISTS `BOD MNJ` (
    report_period CHAR(7) NOT NULL PRIMARY KEY,
    payload LONGTEXT NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS bod_mnj (
    periode DATE NOT NULL,
    tahun_data INT NOT NULL,
    jenis VARCHAR(20) NOT NULL,
    jan DOUBLE NULL, feb DOUBLE NULL, mar DOUBLE NULL,
    apr DOUBLE NULL, mei DOUBLE NULL, jun DOUBLE NULL,
    jul DOUBLE NULL, agu DOUBLE NULL, sep DOUBLE NULL,
    okt DOUBLE NULL, nov DOUBLE NULL, des DOUBLE NULL,
    PRIMARY KEY (periode, tahun_data, jenis)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
