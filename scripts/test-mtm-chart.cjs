const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync('dashboard/mtm-chart.js','utf8'), ctx);
const draw = ctx.window.mtmChartSvg;
let svg = draw({values:[.1,.2,9,.3,.4,-.5]},'2026-09','FARMASI');
assert.equal((svg.match(/data-series=/g)||[]).length,4);
assert.equal((svg.match(/data-growth=/g)||[]).length,2);
for(const label of ['REVENUE','BUDGET SPENDING','FY 2025','YTD SEPTEMBER 2026','Growth 900,00%','Growth -50,00%']) assert(svg.includes(label),label);
assert(!svg.includes('NaN'));
svg = draw({values:[0,0,0,-.3,-.2,1/3]},'2027-02','HCE');
assert(svg.includes('FY 2026'));
assert(svg.includes('YTD FEBRUARI 2027'));
assert(svg.includes('Growth 0,00%'));
assert(!svg.includes('NaN'));
assert(!svg.includes('Infinity'));
assert.equal(draw({values:[null,null,1,null,null,2]},'2026-09','FARMASI'),'');
svg = draw({values:[.1,null,null,null,.2,null]},'2026-09','<test>');
assert.equal((svg.match(/data-series=/g)||[]).length,2);
assert(svg.includes('Growth —'));
assert(svg.includes('&lt;test&gt;'));
console.log('MTM chart passed: two groups, FY/YTD bars, growth labels, dynamic periods, missing/zero/negative values.');
