const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = {window:{}};
vm.runInNewContext(fs.readFileSync('dashboard/tm-bod-previous.js','utf8'), context);
const previous = context.window.TmBodPrevious;
assert.equal(JSON.stringify(previous.period(2026,'Q3')), JSON.stringify({year:2026,quarter:'Q2'}));
assert.equal(JSON.stringify(previous.period(2027,'Q1')), JSON.stringify({year:2026,quarter:'Q4'}));
const rich = {text:'Analisis Q2',html:'<b>Analisis Q2</b>',images:['data:image/png;base64,AAAA']};
const data = {Q2:['GB6','GB5'], 'Q2-section-ids':['base-6','base-5'], 'Q2-section-values':{'base-5':rich}, 'Q2-custom-slides':[{id:'custom-demo',value:'Tambahan Q2'}]};
const before = JSON.stringify(data);
assert.equal(previous.value(data,'Q2','base-6',[]),'GB6');
assert.equal(previous.value(data,'Q2','base-5',[]),rich);
assert.equal(previous.value(data,'Q2','custom-demo',[]),'Tambahan Q2');
assert.equal(previous.value(data,'Q2','new-section',[]),'');
assert.equal(previous.value(data,'Q3','base-5',[]),'');
assert.equal(JSON.stringify(data),before);
assert.equal(previous.value({Q4:['Legacy']},'Q4','base-0',['base-0']),'Legacy');
const items = new Map([['tm-bod-sections-v1',JSON.stringify({Q4:['Legacy']})]]);
const storage = {getItem:key=>items.get(key)||null};
assert.equal(previous.stored(storage,2026).Q4[0],'Legacy');
assert.equal(Object.keys(previous.stored(storage,2027)).length,0);
items.set('tm-bod-sections-v2-2026',JSON.stringify(data));
assert.equal(previous.stored(storage,2026).Q2[0],'GB6');
items.set('tm-bod-sections-v2-2026','invalid json');
assert.equal(Object.keys(previous.stored(storage,2026)).length,0);
console.log('PASS: previous quarter/year, stable IDs, rich content, custom slides, legacy storage, missing data, immutable source');
