// Run after the TM BOD scripts in an isolated browser profile.
(async () => {
 try {
  const check = (value, message) => { if (!value) throw Error(message); };
  const originals = [...document.querySelectorAll('main section.analysis')];
  const base = originals[0];
  base.querySelector('textarea').richEditor.set('Original summary');
  await base.querySelector('.section-save').onclick();
  check(base.querySelector('.rich-editor').contentEditable === 'false', 'base slide locked after save');
  check(base.querySelector('.section-save').hidden && !base.querySelector('.edit-slide').hidden, 'edit replaces save');
  check([...base.querySelectorAll('.editor-toolbar button, input[type=file]')].every(control => control.disabled), 'toolbar and upload locked');
  base.querySelector('.edit-slide').click();
  check(base.querySelector('.rich-editor').contentEditable === 'true', 'edit unlocks base slide');
  await base.querySelector('.section-save').onclick();
  check(document.querySelectorAll('.add-slide-row').length === originals.length, 'add control after every analysis');
  base.nextElementSibling.querySelector('button').click();
  let custom = document.querySelector('section[data-custom-id]');
  check(custom && custom.previousElementSibling === base.nextElementSibling, 'inserted at chosen gap');
  check(custom.querySelector('.editor-toolbar') && custom.querySelector('input[type=file]').multiple, 'editor and images initialized');
  custom.querySelector('.slide-title').value = 'Extra analysis';
  custom.querySelector('textarea').richEditor.set('New slide content');
  await custom.querySelector('.section-save').onclick();
  check(document.querySelector('#preview-slide').textContent.includes('Extra analysis'), 'custom title preview');
  check(document.querySelector('#preview-slide svg image:last-of-type').getAttribute('href').startsWith('data:image/png'), 'custom content rendered');
  check(custom.querySelector('.slide-title').disabled && custom.querySelector('.rich-editor').contentEditable === 'false', 'custom title and body locked');
  custom.querySelector('.edit-slide').click();
  check(!custom.querySelector('.slide-title').disabled, 'custom title unlocks');
  await custom.querySelector('.section-save').onclick();
  const id = custom.dataset.customId;
  const quarter = document.getElementById('quarter');
  const initialQuarter = quarter.value;
  const data = JSON.parse(localStorage.getItem('tm-bod-sections-v1'));
  check(data[initialQuarter][0].text === 'Original summary', 'original values preserved');
  check(data[initialQuarter + '-custom-slides'][0].id === id, 'stable custom ID persisted');
  quarter.value = initialQuarter === 'Q4' ? 'Q1' : 'Q4'; quarter.dispatchEvent(new Event('change'));
  check(!document.querySelector('section[data-custom-id]'), 'quarter isolation');
  quarter.value = initialQuarter; quarter.dispatchEvent(new Event('change'));
  custom = document.querySelector('section[data-custom-id]');
  check(custom._locked && custom.querySelector('.slide-title').disabled, 'custom lock restored');
  check(base._locked && base.querySelector('.rich-editor').contentEditable === 'false', 'base lock restored');
  check(custom.dataset.customId === id && custom.querySelector('.slide-title').value === 'Extra analysis', 'restored title');
  check(custom.querySelector('textarea').value === 'New slide content', 'restored content');
  check(custom.previousElementSibling.previousElementSibling === base, 'restored order');
  custom.nextElementSibling.querySelector('button').click();
  const nested = custom.nextElementSibling.nextElementSibling;
  nested.querySelector('.slide-title').value = 'Nested slide';
  nested.querySelector('textarea').richEditor.set('Nested text');
  await nested.querySelector('.section-save').onclick();
  quarter.value = initialQuarter === 'Q4' ? 'Q1' : 'Q4'; quarter.dispatchEvent(new Event('change'));
  quarter.value = initialQuarter; quarter.dispatchEvent(new Event('change'));
  check(document.querySelectorAll('section[data-custom-id]').length === 2, 'nested slide restoration');
  const parent = document.querySelector('section[data-custom-id]');
  await parent.querySelector('.delete-slide').onclick();
  check(document.querySelectorAll('section[data-custom-id]').length === 1, 'delete one slide only');
  check(!document.querySelector('#preview-slide').textContent.includes('Extra analysis'), 'deleted title removed from preview');
  const afterDelete = JSON.parse(localStorage.getItem('tm-bod-sections-v1'));
  check(afterDelete[initialQuarter + '-custom-slides'].length === 1, 'deletion persisted');
  check(afterDelete[initialQuarter][0].text === 'Original summary', 'base content preserved after delete');
  quarter.value = initialQuarter === 'Q4' ? 'Q1' : 'Q4'; quarter.dispatchEvent(new Event('change'));
  quarter.value = initialQuarter; quarter.dispatchEvent(new Event('change'));
  check(document.querySelectorAll('section[data-custom-id]').length === 1, 'deleted slide stays deleted');
  check(document.querySelector('.slide-title').value === 'Nested slide', 'child retained after deleting parent');
  const search = document.getElementById('report-search'); search.value = 'Nested slide'; search.dispatchEvent(new Event('input'));
  check([...document.querySelectorAll('main section.analysis')].filter(section => !section.hidden).length === 1, 'dynamic slide search');
  document.body.dataset.testResult = 'PASS: insertion, rich editor, save, preview, preserved base data, quarter isolation, nested order, persistent deletion, preserved child slide, dynamic search, save lock, edit unlock, restored locks';
 } catch (error) { document.body.dataset.testResult = 'FAIL: ' + error.stack; }
})();
